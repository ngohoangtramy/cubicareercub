export type ActionStatus = "not-started" | "in-progress" | "completed";
export type StepStatus = "not-started" | "in-progress" | "completed";

export interface ActionResource {
  id: string;
  title: string;
  provider: string;
  kind: "Course" | "YouTube" | "Practice" | "Guide" | "Template" | "Tool" | "Community";
  url: string;
  duration: string;
  cost: "Free" | "Free audit" | "Paid" | "Varies";
  level: "Beginner" | "Intermediate" | "Advanced" | "All levels";
  why: string;
}

export interface ActionOpportunity {
  id: string;
  title: string;
  organiser: string;
  kind: "Hackathon" | "Competition" | "Event" | "Community" | "Internship board" | "Conference";
  url: string;
  timing: string;
  location: string;
  fit: string;
  preparation: string;
}

export interface ActionStep {
  id: string;
  title: string;
  description: string;
  duration: string;
  status: StepStatus;
  checklist: string[];
  deliverable: string;
  evidencePrompt: string;
  resources: ActionResource[];
  opportunities?: ActionOpportunity[];
}

export interface Recommendation {
  id: string;
  title: string;
  type: string;
  priority: "High" | "Medium" | "Low";
  time: string;
  skills: string[];
  reason: string;
  status: ActionStatus;
  deadline?: string;
  outcome: string;
  mentorTip: string;
  steps: ActionStep[];
  evidence: string[];
}

const resource = (
  id: string,
  title: string,
  provider: string,
  kind: ActionResource["kind"],
  url: string,
  duration: string,
  why: string,
  cost: ActionResource["cost"] = "Free",
  level: ActionResource["level"] = "Beginner",
): ActionResource => ({ id, title, provider, kind, url, duration, why, cost, level });

